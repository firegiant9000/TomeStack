using System.Globalization;
using TomeStack.AppService.Persistence;
using TomeStack.RulesCore;

namespace TomeStack.AppService.Packages;

/// <summary>
/// One released TomeStack version as the down-conversion export sees it (D83): the highest schema it reads of each kind,
/// the SRD revisions it bundled, and whether a package may be written for it.
/// </summary>
public sealed record LadderRow(Version Release, int CharacterSchema, int ContentSchema, int GapNoteSchema,
    int FormatVersion, int DatabaseSchema, IReadOnlySet<Guid> BundledRevisionIds, bool OfferedAsTarget);

/// <summary>
/// One entry that keeps a file from opening in the previous minor release: <paramref name="Entry"/> is its path in the package.
/// For a bundled revision the file does not carry (a library backup), it is the path of the character that pins it.
/// </summary>
public sealed record OpensInCause(string Entry, string Kind, Guid Id, string Name, int? SchemaVersion, string? BundledPack, string Message);

/// <summary>The earliest release that opens a file (null: only an unreleased build), what keeps older ones out, and the one warning.</summary>
public sealed record OpensInResult(string? OpensIn, IReadOnlyList<OpensInCause> Causes, IReadOnlyList<Diagnostic> Warnings);

/// <summary>
/// The released versions, ascending, as code (docs/superpowers/specs/2026-10-28-down-conversion-export-spec.md section 1).
/// Patch releases share their minor's row: bundled SRD content ships only in a minor release (owner ruling, 2026-10-27), so a
/// patch never changes <c>src/AppService/Content/</c> and has no row. A new minor adds a row in its release PR, with its bundled
/// set generated by <c>scripts/bundled-ids-at.ps1 -Tag HEAD</c>; a build whose version has no row fails <see cref="CurrentRow"/>,
/// which a test touches (previews use the last row instead).
/// </summary>
public static class ReleaseLadder
{
    // Character, content, gap note, format, database. 0.4.0 is not offered: no v7 writer exists (Q1).
    private static readonly (string Release, int Character, int Content, int GapNote, int Format, int Database, bool Offered)[] Table =
    [
        ("0.4.0", 7, 9, 1, 9, 9, false),
        ("0.5.0", 8, 9, 2, 9, 10, true),
        ("0.6.0", 9, 10, 2, 9, 11, true),
        ("0.7.0", 10, 11, 2, 9, 11, false),
    ];

    private static readonly Lazy<IReadOnlyList<LadderRow>> LazyRows = new(() =>
        [.. Table.Select(t => new LadderRow(new Version(t.Release), t.Character, t.Content, t.GapNote, t.Format, t.Database, ReadBundledSet(t.Release), t.Offered))]);

    /// <summary>The released versions, ascending.</summary>
    public static IReadOnlyList<LadderRow> Rows => LazyRows.Value;

    /// <summary>The row whose major and minor are the running build's (a 0.7.1 build reads the 0.7.0 row).</summary>
    /// <exception cref="InvalidOperationException">The build's minor has no row: add it at the release cut.</exception>
    public static LadderRow CurrentRow => Rows[CurrentIndex];

    /// <summary>The row before <see cref="CurrentRow"/> (the release a file written now is most likely to meet), or null when there is none.</summary>
    public static LadderRow? PreviousMinor => CurrentIndex > 0 ? Rows[CurrentIndex - 1] : null;

    /// <summary>Like <see cref="CurrentRow"/> but never throws: a build whose minor has no row reads the last row, so a preview still works.</summary>
    internal static LadderRow CurrentRowOrLast(string version) => Rows[IndexOrLast(version)];

    /// <summary>The row before <see cref="CurrentRowOrLast"/>, or null when there is none.</summary>
    internal static LadderRow? PreviousMinorFor(string version) => IndexOrLast(version) is > 0 and var i ? Rows[i - 1] : null;

    private static int IndexOrLast(string version)
    {
        var current = new Version(version);
        var index = Rows.ToList().FindIndex(r => r.Release.Major == current.Major && r.Release.Minor == current.Minor);
        return index >= 0 ? index : Rows.Count - 1;
    }

    /// <summary>The offered row whose release is exactly <paramref name="release"/> ("0.6.0"), or null.</summary>
    public static LadderRow? Target(string? release) =>
        Rows.FirstOrDefault(r => r.OfferedAsTarget && string.Equals(r.Release.ToString(3), release, StringComparison.Ordinal));

    /// <summary>
    /// The first row that reads everything the file would hold: every character and revision within its maxima,
    /// <paramref name="gapNoteSchema"/> within its gap note maximum (0 when there are no gap notes), and every bundled
    /// revision id in its set. Null when no released row does: only an unreleased build opens the file.
    /// </summary>
    public static LadderRow? OpensIn(IEnumerable<ContentRevision> revisions, IEnumerable<Character> characters,
        int gapNoteSchema, IEnumerable<Guid> bundledRevisionIds)
    {
        var revisionSchemas = revisions.Select(r => r.SchemaVersion).ToList();
        var characterSchemas = characters.Select(c => c.SchemaVersion).ToList();
        var bundled = bundledRevisionIds.ToList();
        return Rows.FirstOrDefault(row =>
            characterSchemas.All(s => s <= row.CharacterSchema)
            && revisionSchemas.All(s => s <= row.ContentSchema)
            && gapNoteSchema <= row.GapNoteSchema
            && bundled.All(row.BundledRevisionIds.Contains));
    }

    /// <summary>The row's release ("0.6.0"), or "a newer TomeStack" when no released row opens the file.</summary>
    public static string Label(LadderRow? row) => row is null ? "a newer TomeStack" : row.Release.ToString(3);

    private static int CurrentIndex
    {
        get
        {
            var current = new Version(AppVersionStamp.CurrentVersion);
            var index = Rows.ToList().FindIndex(r => r.Release.Major == current.Major && r.Release.Minor == current.Minor);
            return index >= 0
                ? index
                : throw new InvalidOperationException($"The release ladder has no row for TomeStack {current.ToString(3)}: add the row (and its bundled set) at the release cut.");
        }
    }

    private static IReadOnlySet<Guid> ReadBundledSet(string release)
    {
        var name = $"TomeStack.BundledAt.{release}.txt";
        using var stream = typeof(ReleaseLadder).Assembly.GetManifestResourceStream(name)
            ?? throw new InvalidOperationException($"Embedded bundled set {name} is missing.");
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd().Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Select(line => Guid.Parse(line, CultureInfo.InvariantCulture)).ToHashSet();
    }
}
